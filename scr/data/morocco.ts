/**
 * Returns the localized display name for a Moroccan agricultural zone
 */
export function getZoneDisplayName(zone: MoroccanAgriculturalZone, lang: 'ar' | 'en' | 'fr'): string {
  if (lang === 'ar' && zone.nameAr) {
    return zone.nameAr;
  }
  if (lang === 'en' && zone.nameEn) {
    return zone.nameEn;
  }
  return zone.name;
}

/**
 * Returns localized crop label for classification
 */
export function getCropLabel(
  classification: { cropLabelAr?: string; cropLabelEn?: string; cropLabelFr?: string } | null | undefined,
  lang: 'ar' | 'en' | 'fr'
): string {
  if (!classification) {
    if (lang === 'ar') return 'البيانات غير متاحة حالياً';
    if (lang === 'en') return 'Data currently unavailable';
    return 'Données actuellement indisponibles';
  }
  if (lang === 'ar') return classification.cropLabelAr || classification.cropLabelFr || '';
  if (lang === 'en') return classification.cropLabelEn || classification.cropLabelFr || '';
  return classification.cropLabelFr || classification.cropLabelEn || '';
}

